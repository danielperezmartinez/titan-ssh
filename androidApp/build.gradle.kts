// The NDK that cross-compiles the embedded RDP client (ADR-0028 §4); see buildRdpAndroid.
val RDP_NDK_VERSION = "29.0.14206865"

// Release signing key (ADR-0011 §5). Never in the repository: CI passes it through
// environment variables from GitHub Secrets, and a local build can use either
// those or -P properties. Without them the release build is produced unsigned
// and the debug build is unaffected.
fun signingValue(property: String, env: String): String? =
    (findProperty(property) as String?) ?: System.getenv(env)

val releaseKeystore = signingValue("titanKeystoreFile", "TITAN_KEYSTORE_FILE")

// Debug builds from a linked git worktree get their own package and launcher
// label, so parallel sessions install side by side on the shared emulator
// instead of overwriting each other. The main working tree keeps the plain id.
// -PtitanDevSuffix=<name> sets the suffix explicitly; -PtitanDevSuffix= turns it off.
val devSuffix: String = ((findProperty("titanDevSuffix") as String?)
    ?: rootDir.takeIf { File(it, ".git").isFile }?.name.orEmpty())
    .lowercase()
    .replace(Regex("[^a-z0-9_]"), "_")
    .let { if (it.isNotEmpty() && !it[0].isLetter()) "w$it" else it }

// The canary app (ADR-0027) is a separate app: its own id and label, and the
// launcher foreground of src/canary/res (generated by branding/RenderIcon.java)
// laid over main's, so it installs and shows next to the stable app.
val isCanary = rootProject.extra["titanChannel"] == "canary"
val appLabel = if (isCanary) "titan-ssh canary" else "titan-ssh"
val STABLE_APP_ID = "io.github.danielperezmartinez.titanssh"

android {
    namespace = "io.github.danielperezmartinez.titanssh.android"
    compileSdk = libs.versions.android.compileSdk.get().toInt()
    // The NDK that cross-compiles the embedded RDP client (ADR-0028 §4).
    ndkVersion = RDP_NDK_VERSION

    defaultConfig {
        applicationId = STABLE_APP_ID + if (isCanary) ".canary" else ""
        minSdk = libs.versions.android.minSdk.get().toInt()
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        // Single app version, resolved in the root build file (ADR-0011 §3).
        versionCode = rootProject.extra["titanVersionCode"] as Int
        versionName = rootProject.extra["titanVersion"] as String
        manifestPlaceholders["appLabel"] = appLabel
        // The stable app, whose StableConfigProvider the canary reads to copy
        // its configuration (ADR-0027 §4).
        manifestPlaceholders["stableAppId"] = STABLE_APP_ID
        manifestPlaceholders["stableConfigProviderEnabled"] = (!isCanary).toString()
    }

    if (isCanary) {
        // Build-type source sets override main, so the canary's foreground wins.
        sourceSets.getByName("debug").res.srcDir("src/canary/res")
        sourceSets.getByName("release").res.srcDir("src/canary/res")
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = signingValue("titanKeystorePassword", "TITAN_KEYSTORE_PASSWORD")
                keyAlias = signingValue("titanKeyAlias", "TITAN_KEY_ALIAS")
                keyPassword = signingValue("titanKeyPassword", "TITAN_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            if (devSuffix.isNotEmpty()) {
                applicationIdSuffix = ".$devSuffix"
                manifestPlaceholders["appLabel"] = "$appLabel $devSuffix"
                // The debug canary of a worktree copies from that worktree's debug app.
                manifestPlaceholders["stableAppId"] = "$STABLE_APP_ID.$devSuffix"
            }
        }
        release {
            // R8 is on: Compose on Android relies on it for acceptable runtime
            // performance. Crypto providers resolved by reflection are kept in
            // proguard-rules.pro.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    // The encrypted dependency block AGP adds is opaque to third parties;
    // IzzyOnDroid and F-Droid ask for it to be left out.
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
            // The same Bouncy Castle licence ships in each of its jars.
            pickFirsts += "/META-INF/LICENSE.md"
        }
    }
}

